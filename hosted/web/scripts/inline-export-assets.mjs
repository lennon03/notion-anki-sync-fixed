// Writes src/lib/export/assets.generated.ts: the KaTeX stylesheet and Fira Code
// font as data URIs, so exported documents are one self-contained file and the
// server never has to find font files at run time (where node_modules sits
// differs between npm workspaces, Vercel and local runs).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const katexDist = dirname(require.resolve("katex/package.json")) + "/dist";
const firaFile = join(
  dirname(require.resolve("@fontsource/fira-code/package.json")),
  "files/fira-code-latin-400-normal.woff2",
);

// Keep only the woff2 source of each face: every browser that prints a page
// and the PDF renderer read it, and the other two formats triple the size.
let css = readFileSync(join(katexDist, "katex.min.css"), "utf8");
css = css.replace(
  /src:url\(fonts\/([^)]+\.woff2)\) format\("woff2"\)[^;}]*/g,
  (_match, file) =>
    `src:url(data:font/woff2;base64,${readFileSync(join(katexDist, "fonts", file)).toString("base64")}) format("woff2")`,
);
if (css.includes("url(fonts/")) throw new Error("KaTeX font left unembedded");

const out = fileURLToPath(new URL("../src/lib/export/assets.generated.ts", import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/inline-export-assets.mjs. Do not edit.\n` +
    `export const KATEX_CSS = ${JSON.stringify(css)};\n` +
    `export const FIRA_CODE_WOFF2 = ${JSON.stringify(readFileSync(firaFile).toString("base64"))};\n`,
);
